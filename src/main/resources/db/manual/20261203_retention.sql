ALTER TABLE orders ADD COLUMN IF NOT EXISTS retention_hold boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS security_retention_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type varchar(64) NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    retention_hold boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_security_retention_eligible
    ON security_retention_events (occurred_at, id) WHERE NOT retention_hold;
CREATE INDEX IF NOT EXISTS idx_auth_codes_retention ON auth_verification_codes (expires_at, id);
CREATE INDEX IF NOT EXISTS idx_refresh_retention ON refresh_tokens ((LEAST(expires_at, revoked_at)), id);
